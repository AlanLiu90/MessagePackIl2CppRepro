#!/usr/bin/env python3
"""Generate Assets/Scripts/Messages.g.cs: a synthetic message catalog the size of a mid-sized game's protocol.

Every class and struct is marked [GenerateShape], so the PolyType source generator emits a shape for it and for each
collection type its members use (List<T>, T[], Dictionary<K, V>, ...), and Nerdbank.MessagePack can serialize it.

Usage: generate_messages.py [--classes N] [--structs N] [--enums N] [--seed S]
"""
import argparse
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Assets", "Scripts", "Messages.g.cs")

LAYERS = 6
PRIMS = ["int", "long", "float", "double", "bool", "string", "byte[]", "uint", "short"]


def build(n_cls, n_struct, n_enum, rnd):
    enums = [(f"Kind{i:03}", [f"V{j}" for j in range(rnd.randint(3, 10))]) for i in range(n_enum)]
    structs = []
    for i in range(n_struct):
        members = []
        for _ in range(rnd.randint(2, 6)):
            if rnd.random() < 0.2:
                members.append(f"Kind{rnd.randrange(n_enum):03}")
            else:
                members.append(rnd.choice(["int", "long", "float", "double", "bool", "short"]))
        structs.append((f"Pod{i:03}", members))

    # Classes form a layered graph: a class only references classes in the next layer. Long reference chains overflow
    # the stack of the source generator's recursive type collector inside Unity's compiler ("Compiling Scripts" hangs).
    layer_size = max(1, n_cls // LAYERS)
    classes = []
    for i in range(n_cls):
        layer = min(i // layer_size, LAYERS - 1)
        members = []
        for _ in range(rnd.randint(6, 16)):
            r = rnd.random()
            if layer == LAYERS - 1:
                r = min(r, 0.4599)  # last layer: primitives, enums and nullables only
            lo = (layer + 1) * layer_size
            j = rnd.randrange(lo, min(n_cls, lo + layer_size)) if layer < LAYERS - 1 else 0
            e = rnd.randrange(n_enum)
            s = rnd.randrange(n_struct)
            if r < 0.34:
                m = rnd.choice(PRIMS)
            elif r < 0.42:
                m = f"Kind{e:03}"
            elif r < 0.46:
                m = rnd.choice(["int", "long", f"Kind{e:03}"]) + "?"
            elif r < 0.56:
                m = f"Msg{j:04}"
            elif r < 0.60:
                m = f"Pod{s:03}"
            elif r < 0.71:
                m = f"List<Msg{j:04}>"
            elif r < 0.76:
                m = f"Msg{j:04}[]"
            elif r < 0.81:
                m = f"Dictionary<int, Msg{j:04}>"
            elif r < 0.84:
                m = f"Dictionary<string, Msg{j:04}>"
            elif r < 0.87:
                m = f"Dictionary<int, List<Msg{j:04}>>"
            elif r < 0.90:
                m = f"List<Kind{e:03}>"
            elif r < 0.92:
                m = f"Kind{e:03}[]"
            elif r < 0.95:
                m = f"List<Pod{s:03}>"
            elif r < 0.97:
                m = f"Pod{s:03}[]"
            else:
                m = rnd.choice(["HashSet<int>", "Dictionary<int, int>", "Dictionary<string, string>",
                                "Dictionary<int, long>", "List<int[]>", "Dictionary<long, string>"])
            members.append(m)
        classes.append((f"Msg{i:04}", members))
    return enums, structs, classes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classes", type=int, default=600)
    ap.add_argument("--structs", type=int, default=60)
    ap.add_argument("--enums", type=int, default=80)
    ap.add_argument("--seed", type=int, default=12345)
    a = ap.parse_args()
    enums, structs, classes = build(a.classes, a.structs, a.enums, random.Random(a.seed))

    lines = ["// <auto-generated> by Tools/generate_messages.py; do not edit. </auto-generated>",
             "#pragma warning disable CS0649",
             "using System.Collections.Generic;", "using Nerdbank.MessagePack;", "using PolyType;", "", "namespace Repro.Messages", "{"]
    for name, values in enums:
        lines.append(f"    public enum {name} {{ {', '.join(values)} }}")
    lines.append("")
    for kind, types in (("struct", structs), ("class", classes)):
        for name, members in types:
            lines.append(f"    [GenerateShape] public partial {kind} {name}")
            lines.append("    {")
            for k, t in enumerate(members):
                lines.append(f"        [Key({k})] public {t} F{k};")
            lines.append("    }")
        lines.append("")
    lines[-1] = "}"
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT)}: {len(enums)} enums, {len(structs)} structs, {len(classes)} classes")


if __name__ == "__main__":
    main()
