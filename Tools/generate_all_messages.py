#!/usr/bin/env python3
"""Generate Assets/Scripts/AllMessages.g.cs: a payload and a Deserialize call for every catalog class and struct, so the
probe can deserialize the whole catalog (-allMessages).

Each payload is the array a MessagePack-CSharp [Key] type is written as: primitives, enums and structs filled in,
references, collections and nullables nil. The catalog comes from generate_messages.py with the same arguments.

Usage: generate_all_messages.py [--classes N] [--structs N] [--enums N] [--seed S]
"""
import argparse
import os
import random
import struct as pystruct

import generate_messages

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Assets", "Scripts", "AllMessages.g.cs")
NIL = b"\xc0"


def mp_int(n):
    return bytes([n]) if 0 <= n < 128 else b"\xd3" + pystruct.pack(">q", n)


def mp_arr(items):
    n = len(items)
    return (bytes([0x90 | n]) if n < 16 else b"\xdc" + pystruct.pack(">H", n)) + b"".join(items)


PRIM = {
    "int": mp_int(7), "long": mp_int(7), "uint": mp_int(7), "short": mp_int(7),
    "float": b"\xca" + pystruct.pack(">f", 1.5), "double": b"\xcb" + pystruct.pack(">d", 2.5),
    "bool": b"\xc3", "string": b"\xa1s", "byte[]": b"\xc4\x02\x01\x02",
}


def encode(member, structs):
    if member in PRIM:
        return PRIM[member]
    if member.startswith("Kind") and member[4:].isdigit():
        return mp_int(1)
    if member.startswith("Pod") and member[3:].isdigit():
        return mp_arr([encode(m, structs) for m in structs[int(member[3:])][1]])
    return NIL  # references, collections, nullables


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classes", type=int, default=600)
    ap.add_argument("--structs", type=int, default=60)
    ap.add_argument("--enums", type=int, default=80)
    ap.add_argument("--seed", type=int, default=12345)
    a = ap.parse_args()
    _, structs, classes = generate_messages.build(a.classes, a.structs, a.enums, random.Random(a.seed))

    entries = [(name, mp_arr([encode(m, structs) for m in members])) for name, members in classes + structs]
    lines = ["// <auto-generated> by Tools/generate_all_messages.py; do not edit. </auto-generated>",
             "using System;", "using Nerdbank.MessagePack;", "", "namespace Repro.Messages", "{",
             "    /// <summary>Every catalog class, then every struct, with a payload and the call that deserializes it.</summary>",
             "    public static class AllMessages",
             "    {",
             "        public static readonly (string Name, Func<MessagePackSerializer, object> Deserialize)[] Entries =",
             "        {"]
    for i, (name, payload) in enumerate(entries):
        lines.append(f"            (\"{name}\", s => s.Deserialize<{name}>(P{i})),")
    lines += ["        };", ""]
    for i, (name, payload) in enumerate(entries):
        lines.append(f"        private static readonly byte[] P{i} = {{ {', '.join(str(b) for b in payload)} }};")
    lines += ["    }", "}"]
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT)}: {len(classes)} classes, {len(structs)} structs")


if __name__ == "__main__":
    main()
